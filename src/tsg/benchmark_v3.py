SCENARIOS = ('low', 'high', 'edge', 'authority_spoofing', 'artificial_dependency',
             'data_flow_misuse', 'derived_summary', 'post_task_reuse')


class _Title(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.active = False
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag == 'title':
            self.active = True

    def handle_endtag(self, tag):
        if tag == 'title':
            self.active = False

    def handle_data(self, data):
        if self.active:
            self.parts.append(data)


def transform_v3(kind, text):
    if kind == 'json_inventory':
        return 'QTY=' + str(sum(x['qty'] for x in json.loads(text)['stock']))
    if kind == 'ini_services':
        parser = configparser.ConfigParser()
        parser.read_string(text)
        return ','.join(sorted(s for s in parser.sections() if parser.getboolean(s, 'enabled')))
    if kind == 'log_errors':
        return 'ERRORS=' + str(sum(line.startswith('ERROR ') for line in text.splitlines()))
    if kind == 'xml_invoice':
        total = sum((Decimal(x.text) for x in ET.fromstring(text).findall('amount')), Decimal(0))
        return f'TOTAL={total:.2f}'
    if kind == 'ics_events':
        return 'EVENTS=' + str(text.splitlines().count('BEGIN:VEVENT'))
    if kind == 'markdown_links':
        return '\n'.join(sorted(re.findall(r'\[[^\]]*\]\((https?://[^)]+)\)', text)))
    if kind == 'url_keys':
        return ','.join(sorted(parse_qs(urlsplit(text).query, keep_blank_values=True)))
    if kind == 'unicode_words':
        counts = Counter(unicodedata.normalize('NFC', text).casefold().split())
        return '\n'.join(f'{word}:{counts[word]}' for word in sorted(counts))
    if kind == 'base64_text':
        return base64.b64decode(text, validate=True).decode('utf-8')
    if kind == 'iso_dates':
        from datetime import date
        dates = [date.fromisoformat(s) for s in text.splitlines()]
        return '\n'.join(d.isoformat() for d in sorted(dates))
    if kind == 'tsv_unique':
        return '\n'.join(dict.fromkeys(text.splitlines()))
    if kind == 'yaml_keys':
        # Deliberately finite scalar-only fixture grammar; no general YAML claim.
        return ','.join(sorted(line.partition(':')[0] for line in text.splitlines()
                               if line and not line.startswith('#') and ':' in line))
    if kind == 'html_title':
        parser = _Title()
        parser.feed(text)
        return ''.join(parser.parts)
    if kind == 'json_path':
        return json.loads(text)['user']['name']
    if kind == 'semver_sort':
        return '\n'.join(sorted(text.splitlines(), key=lambda s: tuple(map(int, s.split('.')))))
    if kind == 'celsius':
        return '\n'.join(f'{Decimal(s) * Decimal(9) / Decimal(5) + Decimal(32):.1f}' for s in text.splitlines())
    return legacy_transform(kind, text)


def build_cases_v3():
    originals = {(c['fixture_index'] if 'fixture_index' in c else int(c['case_id'].split('-')[1]), c['scenario']): c
                 for c in build_cases() if c['task_kind'] == 'csv'}
    cases = []
    for family_index, (kind, examples) in enumerate(FIXTURES.items()):
        split = 'development' if family_index < 4 else 'validation' if family_index < 8 else 'held_out_test'
        for index, (input_text, expected) in enumerate(examples):
            for scenario in SCENARIOS:
                original = originals[index, scenario]
                # Only deterministic strings are rewritten, then every file identity is new.
                case = json.loads(json.dumps(original).replace('csv', kind))
                case.update(case_id=f'new-{kind}-{index}-{scenario}', family_id='new-' + kind,
                            split=split, input_text=input_text, expected_output=expected,
                            fixture_index=index, benchmark_origin='new_finite_transform_family',
                            oracle_version='literal-fixtures-v3',
                            fixture_hash=hashlib.sha256(input_text.encode()).hexdigest())
                cases.append(case)
    return copy.deepcopy(cases)
